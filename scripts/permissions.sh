#!/usr/bin/env bash
# Разрешения macOS выдаются в окне самого приложения, а не здесь.
#
# Раньше на этом месте стоял мастер на 260 строк: он стирал записи через tccutil, открывал
# панели настроек и перезапускал приложение каждые 20 секунд, ожидая, пока переключатель
# наконец сработает. Всё это лечило один-единственный симптом — приложение подписывалось
# ad-hoc, то есть его «подпись» была хэшем бинарника, и любая пересборка превращала его для
# macOS в другую программу, у которой, естественно, никаких разрешений нет.
#
# Теперь сборка подписывается постоянным сертификатом (scripts/signing-identity.sh), поэтому
# разрешения выдаются один раз и переживают пересборки. Спрашивать о них должно приложение —
# в окне, где видно, что уже выдано, а что нет.
#
# Этому скрипту остаётся немногое: убедиться, что приложение собрано и запущено, и сказать,
# где искать окно.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=/dev/null
source "${SCRIPT_DIR}/_lib.sh"

# ---------------------------------------------------------------------------
# Подпись: без неё разрешения будут слетать после каждой сборки
# ---------------------------------------------------------------------------

step "Подпись приложения"

if security find-identity -v -p codesigning 2>/dev/null |
  grep -qE "Developer ID Application:|LocalVoiceFlow Local Signing"; then
  ok "сертификат на месте — разрешения переживают пересборку"
else
  note "постоянного сертификата нет — создаю"
  "${SCRIPT_DIR}/signing-identity.sh" || die "не удалось создать сертификат для подписи"
  note "Пересоберите приложение, чтобы подпись применилась: make build"
fi

# ---------------------------------------------------------------------------
# Приложение
# ---------------------------------------------------------------------------

step "Приложение"

if [[ ! -d "${LVF_APP_BUNDLE}" ]]; then
  fail "приложение не собрано: ${LVF_APP_BUNDLE}"
  hint "Соберите его: make build"
  exit 1
fi

if pgrep -f "${LVF_APP_BUNDLE}/Contents/MacOS/${LVF_AGENT_BINARY_NAME}" >/dev/null 2>&1; then
  ok "приложение запущено (значок микрофона в строке меню)"
  RUNNING=1
else
  note "приложение не запущено — запускаю"
  open -a "${LVF_APP_BUNDLE}" >/dev/null 2>&1 || die "не удалось запустить ${LVF_APP_BUNDLE}"
  sleep 3
  RUNNING=0
fi

# ---------------------------------------------------------------------------
# Что дальше
# ---------------------------------------------------------------------------

step "Что делать"

# Окно открывается само, когда чего-то не хватает, но у уже запущенного приложения его
# нужно вызвать из меню — снаружи попросить об этом нечем.
if [[ "$RUNNING" == "1" ]]; then
  printf '  Откройте окно настройки: значок микрофона в строке меню →\n'
  printf '  %s«Настроить разрешения…»%s\n\n' "$LVF_C_BOLD" "$LVF_C_RESET"
else
  printf '  Окно настройки открывается само, если каких-то разрешений не хватает.\n'
  printf '  Если оно не появилось — значит всё уже выдано.\n\n'
fi

printf '  В окне у каждого разрешения одна кнопка. macOS покажет своё окно —\n'
printf '  нажмите в нём «Открыть Системные настройки» и включите переключатель\n'
printf '  напротив LocalVoiceFlow. Галочки в окне обновятся сами.\n\n'
printf '  Проверить состояние в любой момент: %smake status%s\n\n' "$LVF_C_BOLD" "$LVF_C_RESET"
lvf_summary
